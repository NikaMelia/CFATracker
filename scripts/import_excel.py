"""Convert the original 'Tracker 1.xlsx' into seed.js for the web app.

Usage:  python scripts/import_excel.py "Tracker 1.xlsx" seed.js
Requires: pip install openpyxl
"""
import json
import re
import sys
from datetime import datetime

import openpyxl

TOPICS = [
    "Economics", "Quantitative Methods", "Corporate Issuers",
    "Financial Statement Analysis", "Equity Investments", "Fixed Income",
    "Derivatives", "Alternative Investments", "Portfolio Management",
    "Ethical and Professional Standards",
]


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def iso(v):
    return v.date().isoformat() if isinstance(v, datetime) else None


def num(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else None


def read_pass(ws, topic_ids, readings_by_name, allow_extras):
    """Return (results, extras) for one sheet (Topics Tracker / Revision)."""
    results, extras = {}, []
    topic = None
    parent = None  # reading id whose sub-items follow (e.g. Reading 91 in Revision)
    for r in range(2, ws.max_row + 1):
        name = ws.cell(r, 2).value
        if not isinstance(name, str) or not name.strip():
            continue
        name = name.strip()
        if name in TOPICS:
            topic, parent = topic_ids[name], None
            continue
        date = iso(ws.cell(r, 4).value)
        f, g = ws.cell(r, 6).value, ws.cell(r, 7).value
        note = ws.cell(r, 8).value
        notes = [n for n in (note if isinstance(note, str) else None,
                             f if isinstance(f, str) else None) if n]
        entry = {"date": date, "correct": num(f), "total": num(g),
                 "note": " / ".join(n.strip() for n in notes)}
        if name in readings_by_name:
            rid = readings_by_name[name]
            parent = None
            # Rows whose F is a formula summing children: keep only the date.
            if isinstance(ws.cell(r, 6).value, str) and ws.cell(r, 6).value.startswith("="):
                entry["correct"] = entry["total"] = None
            results[rid] = entry
            if "Guidance for Standards I" in name and allow_extras:
                parent = rid
        elif allow_extras:
            xid = "x-" + slug(name)
            extras.append({"id": xid, "topicId": topic, "parentId": parent, "name": name})
            results[xid] = entry
    return results, extras


def main(src, dst):
    wb_f = openpyxl.load_workbook(src)  # formulas
    wb = openpyxl.load_workbook(src, data_only=True)  # cached values
    tt = wb["Topics Tracker"]

    topics, readings_by_name, topic_ids = [], {}, {}
    cur = None
    for r in range(2, tt.max_row + 1):
        name = tt.cell(r, 2).value
        if not isinstance(name, str):
            continue
        name = name.strip()
        if name in TOPICS:
            cur = {"id": slug(name), "name": name, "readings": []}
            topic_ids[name] = cur["id"]
            topics.append(cur)
        elif cur is not None:
            m = re.match(r"Reading (\d+)\s+(.*)", name)
            rid = "r" + m.group(1) if m else "r-" + slug(name)
            cur["readings"].append({"id": rid, "name": name})
            readings_by_name[name] = rid

    # Weights / conspect from the right-hand summary table (N..T)
    for r in range(3, 13):
        tname = tt.cell(r, 14).value
        if tname not in topic_ids:
            continue
        t = next(t for t in topics if t["name"] == tname)
        t["weightRange"] = tt.cell(r, 12).value or ""
        t["weight"] = num(tt.cell(r, 20).value) or 0
        t["conspect"] = tt.cell(r, 18).value or "Not started"

    study, _ = read_pass(tt, topic_ids, readings_by_name, allow_extras=False)
    revision, extras = read_pass(wb["Revision"], topic_ids, readings_by_name, allow_extras=True)

    ht = wb["Hours Tracker"]
    hours = []
    for r in range(10, ht.max_row + 1):
        d, h, t = ht.cell(r, 3).value, ht.cell(r, 4).value, ht.cell(r, 5).value
        if num(h):
            hours.append({"id": f"h{r}", "date": iso(d), "hours": h, "topicId": topic_ids.get(t, ""), "note": ""})

    hours_goal = 300
    m = re.match(r"=(\d+)-", str(wb_f["Hours Tracker"]["D5"].value or ""))
    if m:
        hours_goal = int(m.group(1))

    data = {
        "version": 1,
        "settings": {
            "examDate": iso(ht["D3"].value) or "",
            "startDate": iso(tt["D3"].value) or "",
            "hoursGoal": hours_goal,
            "level": "Level I",
        },
        "topics": topics,
        "passes": [
            {"id": "study", "name": "First pass", "results": study, "extras": []},
            {"id": "revision", "name": "Revision", "results": revision, "extras": extras},
        ],
        "hours": hours,
    }
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/import_excel.py from the original Excel tracker.\n")
        fh.write("window.CFA_SEED = ")
        json.dump(data, fh, ensure_ascii=False, indent=1)
        fh.write(";\n")
    n = sum(len(t["readings"]) for t in topics)
    print(f"{len(topics)} topics, {n} readings, {len(study)} study results, "
          f"{len(revision)} revision results ({len(extras)} extra items), {len(hours)} hour entries")


if __name__ == "__main__":
    main(*(sys.argv[1:3] if len(sys.argv) >= 3 else ("Tracker 1.xlsx", "seed.js")))
